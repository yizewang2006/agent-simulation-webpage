// Initialize a property object
export function initializePropertyValue(property) { // from paper
    // if a user-defined value is available, use that
    if (property.vinit !== null) return property.vinit

    // generate a random value, if none exists
    if (property.type === PROPERTY_TYPE.NUMERICAL) {
        const [lower, upper] = property.range;
        return lower + Math.random() * (upper - lower);
    }

    // else, if categorical property, use a random index
    else if (property.type === PROPERTY_TYPE.CATEGORICAL) {
        const randomIndex = Math.floor(Math.random() * property.range.length);
        return property.range[randomIndex]
    }
}

// Normalize a property's definition (when created)
export function normalizePropertyDefinition(propertyDraft) {
    const property = {
        id: propertyDraft.id ?? `PRP-${crypto.randomUUID().toUpperCase()}`, // assign id if not provided
        name: propertyDraft.name.trim(),
        type: propertyDraft.type,
        assignments: {
            ...propertyDraft.assignments,
            [ENTITY_TYPES.OBSTACLE]: {
                ...propertyDraft.assignments[ENTITY_TYPES.OBSTACLE],
            },
        },
    }

    if (propertyDraft.type == PROPERTY_TYPE.NUMERICAL) {
        property.range = [
            Number(propertyDraft.lower),
            Number(propertyDraft.upper)
        ];

        property.vinit = propertyDraft.vinit === "" || propertyDraft.vinit === null
            ? null
            : Number(propertyDraft.vinit);
    }

    else if (propertyDraft.type == PROPERTY_TYPE.CATEGORICAL) {
        property.range = propertyDraft.range
        .map((value) => value.trim()) // Trim spaces for each input
        .filter(Boolean); // Delete empty strings

        property.vinit = propertyDraft.vinit === "" || propertyDraft.vinit === null
            ? null
            : propertyDraft.vinit.trim();
    }

    // After normalization, validate
    return validatePropertyDefinition(property);
}

// Validates if a property can/not be created
export function validatePropertyDefinition(property) {
    // Property names come from a text input, so only an empty name is invalid.
    if (!property.name.trim()) {
        throw new Error("Property name cannot be empty.");
    }

    const obstacleAssignments = property.assignments[ENTITY_TYPES.OBSTACLE];
    if (
        property.assignments[ENTITY_TYPES.AGENT] !== true
        && obstacleAssignments.enabled !== true
    ) {
        throw new Error("Select at least one entity assignment.");
    }

    // Numerical properties use two numbers as their lower and upper bounds.
    if (property.type === PROPERTY_TYPE.NUMERICAL) {
        const [lower, upper] = property.range;

        // Empty or non-numeric form values become NaN during normalization.
        if (!Number.isFinite(lower) || !Number.isFinite(upper)) {
            throw new Error("Numerical range must contain valid numbers.");
        }

        if (lower >= upper) {
            throw new Error("Numerical lower range must be smaller than upper range.");
        }

        // A null vinit means an initial value will be generated later.
        if (
            property.vinit !== null
            && (
                !Number.isFinite(property.vinit)
                || property.vinit < lower
                || property.vinit > upper
            )
        ) {
            throw new Error("Numerical initial value must stay inside the range.");
        }
    }

    // Categorical properties use a list of allowed text values as their range.
    if (property.type === PROPERTY_TYPE.CATEGORICAL) {
        if (property.range.length === 0) {
            throw new Error("Categorical range cannot be empty.");
        }

        // The paper defines the categorical range as a set, so values must be unique.
        if (new Set(property.range).size !== property.range.length) {
            throw new Error("Categorical range cannot contain duplicate values.");
        }

        // A provided initial value must be one of the allowed categories.
        if (property.vinit !== null && !property.range.includes(property.vinit)) {
            throw new Error("Categorical initial value must be in the range.");
        }
    }

    return property;
}

export function getPropertyValue(entity, property) {
    if (!supportsProperty(entity, property)) {
        throw new Error(`${entity.name} does not have property "${property.name}".`);
    }

    return entity.propertyValues[property.id]
}

export function setPropertyValue(entity, property, value) {
    if (property.type === PROPERTY_TYPE.NUMERICAL) {
    const [lower, upper] = property.range;

    // sanity check
    if (!Number.isFinite(value)) {
      throw new Error("Numerical Property value must be a valid number.");
    }

    if (value < lower || value > upper) {
      throw new Error(`Property value must stay between ${lower} and ${upper}.`);
        }
    }

    if (property.type === PROPERTY_TYPE.CATEGORICAL && !property.range.includes(value)) {
        throw new Error(
        `Property value must be one of: ${property.range.join(", ")}.`
        );
    }

    entity.propertyValues[property.id] = value;
}

export function supportsProperty(entity, property) {
    return Object.hasOwn(entity.propertyValues, property.id)
}

export function assignPropertyToEntity(entity, property) {
    const assignment = property.assignments[entity.entityType];

    const isAssigned = typeof assignment === "boolean"
        ? assignment
        : assignment.enabled && assignment[entity.shapeType];

    // Report that this Entity should no longer store this Property.
    if (!isAssigned) return false;

    // Preserve the current value when an edited Property remains assigned.
    if (!supportsProperty(entity, property)) {
        entity.propertyValues[property.id] =
            initializePropertyValue(property);
    }

    return true;
}

// Comparison
export function getPropertyDifference(self, neighbor, property) {
    return (
        getPropertyValue(neighbor, property) - getPropertyValue(self, property)
    );
}